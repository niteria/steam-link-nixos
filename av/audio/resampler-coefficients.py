#!/usr/bin/env python3
"""Write the 44.1 -> 48 kHz polyphase table for pcm-sink as a C header.

48000/44100 = 160/147: interpolate by 160, decimate by 147. The prototype is a
Kaiser-windowed sinc at the 7.056 MHz intermediate rate; each of the 160 phases
has TAPS input-rate taps, scaled by 160 for unity passband gain and stored as
Q15. Pure Python, so the build needs no numerical packages."""
import math
import sys

L, M, TAPS, CUTOFF, BETA = 160, 147, 48, 21000.0, 8.0
RATE = 44100.0 * L


def bessel_i0(x):
    total, term, k = 1.0, 1.0, 1
    while term > 1e-12 * total:
        term *= (x / (2 * k)) ** 2
        total += term
        k += 1
    return total


length = L * TAPS
centre = (length - 1) / 2
norm = bessel_i0(BETA)
prototype = []
for n in range(length):
    t = n - centre
    x = 2 * CUTOFF / RATE * t
    sinc = 1.0 if t == 0 else math.sin(math.pi * x) / (math.pi * x)
    window = bessel_i0(BETA * math.sqrt(max(0.0, 1 - (t / centre) ** 2))) / norm
    prototype.append(2 * CUTOFF / RATE * sinc * window * L)
rows = []
for phase in range(L):
    taps = [prototype[phase + k * L] for k in range(TAPS)]
    quantized = [max(-32768, min(32767, round(c * 32768))) for c in taps]
    # Keep every phase's DC gain exactly unity after rounding.
    quantized[TAPS // 2] += 32768 - sum(quantized)
    rows.append(quantized)
out = sys.stdout
out.write("/* Generated by resampler-coefficients.py: L=%d M=%d taps=%d cutoff=%g Hz beta=%g. */\n"
          % (L, M, TAPS, CUTOFF, BETA))
out.write("#define RS_L %d\n#define RS_M %d\n#define RS_TAPS %d\n" % (L, M, TAPS))
out.write("static const int16_t rs_coefficients[RS_L][RS_TAPS]={\n")
for row in rows:
    out.write("    {" + ",".join(str(c) for c in row) + "},\n")
out.write("};\n")
